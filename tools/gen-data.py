"""Generate crates/hw-data/src/generated.rs from reference/constants/constants-v1.jsonl and reference/tas."""
import json, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
recs = [json.loads(l) for l in (root / "reference/constants/constants-v1.jsonl").read_text().splitlines() if l.strip()]
NAN = "[0x7FF80000, 0x00000000]"

def w(hexs):
    return "[0x%s, 0x%s]" % (hexs[:8], hexs[8:])

def b(v):
    return "true" if v else "false"

def num(rec, key):
    v = rec.get(key)
    if v is None or isinstance(v, bool):
        return NAN
    return w(v)

SHAPE_CLASS = {"RectangleShape": "ShapeClass::Rectangle", "CircleShape": "ShapeClass::Circle", "TriangleShape": "ShapeClass::Triangle"}
SPECIAL_KIND = {"VanRef": "Van", "TableRef": "Table", "MineRef": "Mine", "IBeamRef": "IBeam", "LogRef": "Log", "SpringBoxRef": "SpringBox",
                "SpikesRef": "Spikes", "WreckingBallRef": "WreckingBall", "FanRef": "Fan", "FinishLineRef": "FinishLine",
                "SoccerBallRef": "SoccerBall", "MeteorRef": "Meteor", "BoostRef": "Boost", "Building1Ref": "Building1", "Building2Ref": "Building2"}

def cls(rec):
    return rec["class"].split("::")[-1]

def shape_rec(r):
    return ("ShapeRec { class: %s, x: %s, y: %s, rotation: %s, scale_x: %s, scale_y: %s, width: %s, height: %s, interactive: %s, immovable: %s, sleeping: %s, density: %s }"
            % (SHAPE_CLASS[cls(r)], w(r["x"]), w(r["y"]), w(r["rotation"]), w(r["scaleX"]), w(r["scaleY"]), w(r["width"]), w(r["height"]),
               b(r.get("interactive", True)), b(r.get("immovable", False)), b(r.get("sleeping", False)), num(r, "density")))

def special_rec(r):
    return ("SpecialRec { kind: SpecialKind::%s, x: %s, y: %s, rotation: %s, scale_x: %s, scale_y: %s, width: %s, height: %s, immovable2: %s, num_spikes: %s, num_panels: %s, num_floors: %s, floor_width: %s, rope_length: %s, spring_delay: %s, shape_width: %s, shape_height: %s }"
            % (SPECIAL_KIND[cls(r)], w(r["x"]), w(r["y"]), w(r["rotation"]), w(r["scaleX"]), w(r["scaleY"]), w(r["width"]), w(r["height"]),
               b(r.get("immovable2", False)), num(r, "numSpikes"), num(r, "numPanels"), num(r, "numFloors"), num(r, "floorWidth"),
               num(r, "ropeLength"), num(r, "springDelay"), num(r, "shapeWidth"), num(r, "shapeHeight")))

def body_ref(s):
    if s == "levelBody":
        return "BodyRef::LevelBody"
    kind, idx = s.split(":")
    return {"shape": "BodyRef::Shape(%s)", "special": "BodyRef::Special(%s)", "group": "BodyRef::Group(%s)"}[kind] % idx

out = ["// GENERATED by tools/gen-data.py from reference/constants/constants-v1.jsonl -- do not edit.",
       "use crate::*;", ""]
levels = [r for r in recs if r["kind"] == "level"]
for lv in levels:
    lid = lv["level"]
    shapes = [r for r in recs if r["kind"] == "shape" and r["level"] == lid]
    specials = [r for r in recs if r["kind"] == "special" and r["level"] == lid]
    groups = [r for r in recs if r["kind"] == "group" and r["level"] == lid]
    joints = [r for r in recs if r["kind"] == "joint" and r["level"] == lid]
    assert [r["index"] for r in shapes] == list(range(len(shapes)))
    out.append("const LEVEL_%d_SHAPES: [ShapeRec; %d] = [" % (lid, len(shapes)))
    for r in shapes:
        out.append("    %s," % shape_rec(r))
    out.append("];")
    out.append("const LEVEL_%d_SPECIALS: [SpecialRec; %d] = [" % (lid, len(specials)))
    for r in specials:
        out.append("    %s," % special_rec(r))
    out.append("];")
    for g in groups:
        gi = g["index"]
        gs = [r for r in recs if r["kind"] == "groupshape" and r["level"] == lid and r["group"] == gi]
        gp = [r for r in recs if r["kind"] == "groupspecial" and r["level"] == lid and r["group"] == gi]
        out.append("const LEVEL_%d_GROUP_%d_SHAPES: [ShapeRec; %d] = [" % (lid, gi, len(gs)))
        for r in gs:
            out.append("    %s," % shape_rec(r))
        out.append("];")
        out.append("const LEVEL_%d_GROUP_%d_SPECIALS: [SpecialRec; %d] = [" % (lid, gi, len(gp)))
        for r in gp:
            out.append("    %s," % special_rec(r))
        out.append("];")
    out.append("const LEVEL_%d_GROUPS: [GroupRec; %d] = [" % (lid, len(groups)))
    for g in groups:
        gi = g["index"]
        out.append("    GroupRec { x: %s, y: %s, rotation: %s, offset_x: %s, offset_y: %s, sleeping: %s, shapes_used: %d, shapes: &LEVEL_%d_GROUP_%d_SHAPES, specials: &LEVEL_%d_GROUP_%d_SPECIALS },"
                   % (w(g["x"]), w(g["y"]), w(g["rotation"]), w(g["offsetX"]), w(g["offsetY"]), b(g["sleeping"]), g["shapesUsed"], lid, gi, lid, gi))
    out.append("];")
    out.append("const LEVEL_%d_JOINTS: [JointRec; %d] = [" % (lid, len(joints)))
    for j in joints:
        out.append("    JointRec { x: %s, y: %s, limit: %s, upper_angle: %s, lower_angle: %s, motor: %s, torque: %s, speed: %s, collide_self: %s, body1: %s, body2: %s },"
                   % (w(j["x"]), w(j["y"]), b(j["limit"]), w(j["upperAngle"]), w(j["lowerAngle"]), b(j["motor"]), w(j["torque"]), w(j["speed"]), b(j["collideSelf"]), body_ref(j["body1"]), body_ref(j["body2"])))
    out.append("];")
out.append("pub const LEVELS: [LevelTable; %d] = [" % len(levels))
for lv in levels:
    lid = lv["level"]
    st = lv["start"]
    out.append("    LevelTable { id: %d, start_x: %s, start_y: %s, start_character: %d, bd_index: %d, shapes: &LEVEL_%d_SHAPES, specials: &LEVEL_%d_SPECIALS, groups: &LEVEL_%d_GROUPS, joints: &LEVEL_%d_JOINTS },"
               % (lid, w(st["x"]), w(st["y"]), st["characterIndex"], lv["bdIndex"], lid, lid, lid, lid))
out.append("];")
for n in range(1, 5):
    for kind, name in (("charguide%d" % n, "GUIDE"), ("kidguide%d" % n, "KID_GUIDE"), ("charsrc%d" % n, "SRC")):
        parts = [r for r in recs if r["kind"] == kind]
        out.append("const CHAR_%d_%s: [CharPart; %d] = [" % (n, name, len(parts)))
        for r in parts:
            out.append('    CharPart { name: "%s", index: %d, x: %s, y: %s, rotation: %s, scale_x: %s, scale_y: %s, width: %s, height: %s },'
                       % (r["name"], r["index"], w(r["x"]), w(r["y"]), w(r["rotation"]), w(r["scaleX"]), w(r["scaleY"]), w(r["width"]), w(r["height"])))
        out.append("];")
out.append("pub const CHARACTERS: [CharTable; 4] = [")
for n in range(1, 5):
    out.append("    CharTable { index: %d, guide: &CHAR_%d_GUIDE, kid_guide: &CHAR_%d_KID_GUIDE, src: &CHAR_%d_SRC }," % (n, n, n, n))
out.append("];")
idx = json.loads((root / "reference/tas/index.json").read_text())
out.append("pub const TAS_STRINGS: [TasString; %d] = [" % len(idx))
for e in idx:
    bits = (root / "reference/tas" / e["file"]).read_text().strip()
    out.append('    TasString { name: "%s", file: "%s", trace: "%s", level: %d, character: %d, frames: %d, bits: "%s" },' % (e["name"], e["file"], e["trace_stem"], e["level"], e["character"], e["frames"], bits))
out.append("];")
(root / "crates/hw-data/src/generated.rs").write_text("\n".join(out) + "\n")
print("generated", len(out), "lines for", [lv["level"] for lv in levels])

# Runtime damage lookups must not carry Flash names or slice pointers into SPIR-V.
# Keep these keys explicit so a new runtime lookup requires a deliberate addition.
runtime_names = ["spineAnchor", "footShape", "sevArm1Shape", "sevLeg1Shape", "sevLeg2Shape"]
runtime_names += ["%sVert%d" % (part, i) for part, count in
                  [("helmet", 4), ("fork", 3), ("broken", 4), ("seat", 3)] for i in range(1, count + 1)]
def variant(name):
    return name[0].upper() + name[1:]
runtime = ["// GENERATED by tools/gen-data.py from the same measured character records.",
           "use crate::GuideNumbers;", "#[derive(Clone, Copy, Debug, PartialEq, Eq)]",
           "#[repr(u32)]", "pub enum GuideKey {"]
runtime += ["    %s," % variant(name) for name in runtime_names]
runtime += ["}", "impl GuideKey {", "    pub const ALL: [Self; %d] = [" % len(runtime_names)]
runtime += ["        Self::%s," % variant(name) for name in runtime_names]
runtime += ["    ];", "    pub const fn name(self) -> &'static str {", "        match self {"]
runtime += ['            Self::%s => "%s",' % (variant(name), name) for name in runtime_names]
runtime += ["        }", "    }", "}", "#[inline]",
            "pub fn guide_numbers(index: u32, child: u32, key: GuideKey) -> Option<GuideNumbers> {",
            "    match (index, child, key) {"]
for n in range(1, 5):
    for child, kind in [(0, "charguide%d" % n), (1, "kidguide%d" % n)]:
        first = {}
        for r in recs:
            if r["kind"] == kind:
                first.setdefault(r["name"], r)  # match the original find-first lookup
        for name in runtime_names:
            if name not in first:
                continue
            r = first[name]
            runtime.append("        (%d, %d, GuideKey::%s) => Some(GuideNumbers { index: %d, x: %s, y: %s, rotation: %s, scale_x: %s, scale_y: %s, width: %s, height: %s })," %
                           (n, child, variant(name), r["index"], w(r["x"]), w(r["y"]), w(r["rotation"]), w(r["scaleX"]), w(r["scaleY"]), w(r["width"]), w(r["height"])))
runtime += ["        _ => None,", "    }", "}"]
(root / "crates/hw-data/src/runtime_guides.rs").write_text("\n".join(runtime) + "\n")
